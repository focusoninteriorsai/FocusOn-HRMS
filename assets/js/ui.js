// Safe Toast Notification
export function showToast(message, type = 'info', durationMs = 4000) {
  let container = document.getElementById('toast-container');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toast-container';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;
  toast.setAttribute('role', 'alert');

  const iconWrap = document.createElement('div');
  iconWrap.innerHTML = type === 'success' ? ICONS.checkCircle : (type === 'error' ? ICONS.alertCircle : ICONS.bell);

  const textWrap = document.createElement('div');
  textWrap.style.flex = '1';
  textWrap.style.fontSize = '0.875rem';
  textWrap.textContent = message;

  toast.appendChild(iconWrap);
  toast.appendChild(textWrap);
  container.appendChild(toast);

  // Trigger entrance
  requestAnimationFrame(() => {
    toast.classList.add('show');
  });

  setTimeout(() => {
    toast.classList.remove('show');
    setTimeout(() => {
      if (toast.parentNode) toast.parentNode.removeChild(toast);
    }, 300);
  }, durationMs);
}

// Modal Dialog
export function openModal({ title, contentNode, onClose, maxWidth = '500px' }) {
  let backdrop = document.getElementById('global-modal-backdrop');
  if (!backdrop) {
    backdrop = document.createElement('div');
    backdrop.id = 'global-modal-backdrop';
    backdrop.className = 'modal-backdrop';
    document.body.appendChild(backdrop);
  }

  backdrop.innerHTML = '';
  const box = document.createElement('div');
  box.className = 'modal-box';
  box.style.maxWidth = maxWidth;

  const header = document.createElement('div');
  header.className = 'astra-card-header';
  header.style.marginBottom = '1.25rem';

  const titleEl = document.createElement('h3');
  titleEl.className = 'astra-card-title';
  titleEl.textContent = title;

  const closeBtn = document.createElement('button');
  closeBtn.className = 'btn-icon';
  closeBtn.setAttribute('aria-label', 'Close dialog');
  closeBtn.innerHTML = ICONS.x;
  closeBtn.onclick = () => closeModal();

  header.appendChild(titleEl);
  header.appendChild(closeBtn);
  box.appendChild(header);

  if (contentNode) {
    box.appendChild(contentNode);
  }

  backdrop.appendChild(box);
  requestAnimationFrame(() => backdrop.classList.add('open'));

  const handleEsc = (e) => {
    if (e.key === 'Escape') closeModal();
  };
  window.addEventListener('keydown', handleEsc);

  window.__activeModalClose = () => {
    backdrop.classList.remove('open');
    window.removeEventListener('keydown', handleEsc);
    if (onClose) onClose();
  };
}

export function closeModal() {
  if (window.__activeModalClose) {
    window.__activeModalClose();
    window.__activeModalClose = null;
  }
}

// Confirm Dialog
export function confirmDialog(title, message, confirmText = 'Confirm', danger = false) {
  return new Promise((resolve) => {
    const content = document.createElement('div');
    const msg = document.createElement('p');
    msg.style.marginBottom = '1.5rem';
    msg.textContent = message;
    content.appendChild(msg);

    const btnRow = document.createElement('div');
    btnRow.style.display = 'flex';
    btnRow.style.justifyContent = 'flex-end';
    btnRow.style.gap = '0.75rem';

    const cancelBtn = document.createElement('button');
    cancelBtn.className = 'btn btn-secondary';
    cancelBtn.textContent = 'Cancel';
    cancelBtn.onclick = () => {
      closeModal();
      resolve(false);
    };

    const confirmBtn = document.createElement('button');
    confirmBtn.className = danger ? 'btn btn-danger' : 'btn btn-primary';
    confirmBtn.textContent = confirmText;
    confirmBtn.onclick = () => {
      closeModal();
      resolve(true);
    };

    btnRow.appendChild(cancelBtn);
    btnRow.appendChild(confirmBtn);
    content.appendChild(btnRow);

    openModal({
      title,
      contentNode: content,
      onClose: () => resolve(false)
    });
  });
}
